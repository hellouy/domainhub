import { drizzle } from "drizzle-orm/node-postgres"
import { Pool } from "pg"
import * as schema from "./schema"

const configuredConnectionString =
  process.env.tldbi_POSTGRES_URL ?? process.env.tldbi_POSTGRES_URL_NON_POOLING ?? process.env.DATABASE_URL
const connectionUrl = configuredConnectionString ? new URL(configuredConnectionString) : null
const isSupabaseConnection =
  connectionUrl?.hostname.endsWith(".pooler.supabase.com") || connectionUrl?.hostname.endsWith(".supabase.co")

if (isSupabaseConnection) {
  // pg URL SSL options replace the explicit CA passed to Pool.
  for (const parameter of ["sslmode", "sslrootcert", "sslcert", "sslkey", "sslpassword"]) {
    connectionUrl?.searchParams.delete(parameter)
  }
}
const connectionString = connectionUrl?.toString()

